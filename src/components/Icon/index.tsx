type IconProps = {
  icon?: string
  className?: string
  'aria-hidden'?: boolean
  size?: number
}

export const Icon: React.FC<IconProps> = ({
  icon,
  className,
  'aria-hidden': ariaHidden,
  size = 24,
}) => {
  if (!icon) return null

  const IconComponent = iconMap[icon]

  if (!IconComponent) return null

  return <IconComponent className={className} size={size} aria-hidden={ariaHidden} />
}
